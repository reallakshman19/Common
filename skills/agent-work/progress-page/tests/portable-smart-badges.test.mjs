import assert from 'node:assert/strict';
import test from 'node:test';
import {smartBadgesForScope,smartBadgeText} from '../viewer/smart-badges.js';
import {autoGeneratedTimelineCards,autoGeneratedPageBrief} from '../viewer/timeline-live.js';
import {agentStartModel,agentStartTaskText} from '../viewer/agent-start.js';
import {oracleContinuityModel} from '../viewer/oracle-continuity.js';
import {wbsGroups} from '../viewer/progress.js';

const SRC='https://github.com/acme/product/issues/180';
const project={
 index:{project:{key:'demo',title:'Demo',aim:'Work with original sources',aimSrc:SRC},
   milestones:{M12:{wbs:'3',name:'Onboard',capSrc:SRC},M13:{wbs:'3.1',name:'Milestone G1',full:'Do bounded G1',capSrc:SRC}},
   revisions:[{id:'R1',status:'current'}],
   groups:{geom:{title:'Geometry'},cont:{title:'Oracle continuity'}}},
 cards:{g1:{milestone:'M13',label:'G1',state:'IN_PROGRESS',src:SRC,refs:[],next:{actor:'Reviewer',text:'Review source'}},
   oracle:{group:'cont',milestone:'M12',label:'Oracle continuity handover',state:'IN_PROGRESS',
      who:{role:'Oracle'},src:SRC},
   coder:{group:'cont',milestone:'M12',label:'Builder onboarding',who:{role:'Coder'},src:SRC}},
 audit:{events:[{id:'DEMO-R-0001',card:'g1',kind:'UPDATE',source:SRC,at:'2026-10-29T00:00:00Z',
   summary:'Source observed, acceptance not established',actor:'Page writer',rev:'R1'}]}
};

test('stable sourced badge IDs do not infer PLAN/FIXTURE/acceptance from free text',()=>{
 const badges=smartBadgesForScope(project,{cardId:'g1',milestoneId:'M13'});
 assert.deepEqual(badges.map(x=>x.id),['demo/AIM/project','demo/WBS/3.1','demo/ROADMAP/M13']);
 assert.ok(badges.every(x=>x.evidence==='SOURCE_LINKED'));
 assert.match(smartBadgeText(badges),/demo\/WBS\/3\.1/);
 assert.deepEqual(smartBadgesForScope(project,{cardId:'g1',milestoneId:'M12'}),[]);
});
test('same badge IDs are reused in automatic Timeline and exact Agent Start packet',()=>{
 const items=autoGeneratedTimelineCards(project);
 assert.equal(items.length,1);
 const badges=smartBadgesForScope(project,{cardId:'g1'});
 assert.deepEqual(items[0].badges.map(x=>x.id),badges.map(x=>x.id));
 assert.match(autoGeneratedPageBrief(items[0]),/demo\/AIM\/project/);
 const family=wbsGroups(project.index).find(x=>x.key==='wbs:3');
 const model=agentStartModel(project,{family,step:'M13',cardId:'g1',revision:'R1'});
 assert.equal(model.selected?.id,'g1');
 assert.match(agentStartTaskText(model),/demo\/WBS\/3\.1/);
});
test('Oracle handover badges never convert coder onboarding into Oracle authority',()=>{
 const m=oracleContinuityModel(project);
 assert.deepEqual(m.cards.map(x=>x.id),['oracle']);
 assert.ok(m.cards[0].smartBadges.some(x=>x.id==='demo/ORACLE_CONTINUITY/oracle'));
 assert.ok(!m.cards.some(x=>x.id==='coder'));
});
